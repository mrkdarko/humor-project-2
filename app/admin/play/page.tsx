import Link from "next/link";
import { requireAdmin } from "@/lib/auth";
import { Composer } from "./composer";
import { VoteControls } from "./vote-controls";

type FeedRow = {
  id: string; content: string; prompt: string; topic: string; provider: string;
  user_id: string; created_at: string; upvotes: number; downvotes: number; own_vote: number;
};
type Draft = { id: string; prompt: string; topic: string; created_at: string };
const views = ["newest", "top", "mine"] as const;
const topics = ["Campus", "Dorm life", "NYC"] as const;

export default async function PlayPage({ searchParams }: {
  searchParams: Promise<{ view?: string; topic?: string; page?: string }>;
}) {
  const { supabase, user } = await requireAdmin();
  const params = await searchParams;
  const view = views.find(item => item === params.view) || "newest";
  const topic = topics.find(item => item === params.topic);
  const page = Math.min(1000, Math.max(1, Number.parseInt(params.page || "1", 10) || 1));
  const href = (nextView: string, nextTopic: string | null = topic || null, nextPage = 1) => `/admin/play?${new URLSearchParams({
    view: nextView, ...(nextTopic ? { topic: nextTopic } : {}),
    ...(nextPage > 1 ? { page: String(nextPage) } : {}),
  })}`;
  const [{ data: feed, error: feedError }, { data: drafts, error: draftError }] = await Promise.all([
    supabase.rpc("get_caption_feed", { p_view: view, p_topic: topic || null, p_offset: (page - 1) * 20 }),
    supabase.from("generations").select("id, prompt, topic, created_at").eq("user_id", user.id).eq("status", "queued").order("created_at", { ascending: false }).limit(10),
  ]);
  const rows = (feed || []) as FeedRow[];
  return <>
    <div className="page-heading"><div><div className="eyebrow dark">PLAYER MODE <span>●</span> YOUR COMMUNITY</div><h1>Play the stage <span className="heading-spark">★</span></h1><p>Post a prompt, discover captions, and rate the laughs.</p></div><Link href="/admin/profile" className="solid-button">MY PROFILE</Link></div>
    {(feedError || draftError) && <div className="alert" role="alert">Could not load the community feed. Check the regular Humor Project database functions and permissions.</div>}
    <div className="play-grid">
      <section className="panel play-feed" aria-label="Community captions">
        <div className="play-feed-header"><div><div className="eyebrow dark">COMMUNITY FEED</div><h2>CAPTION ARCADE</h2></div><div className="filter-tabs">{views.map(item => <Link key={item} href={href(item)} className={view === item ? "selected" : ""} aria-current={view === item ? "page" : undefined}>{item === "mine" ? "MY POSTS" : item.toUpperCase()}</Link>)}</div></div>
        <div className="play-topic-row"><Link href={href(view, null)} className={!topic ? "selected" : ""}>ALL TOPICS</Link>{topics.map(item => <Link key={item} href={href(view, item)} className={topic === item ? "selected" : ""}>{item.toUpperCase()}</Link>)}</div>
        {!feedError && !rows.length && <div className="empty-state"><span>👻</span><strong>No captions here yet</strong><p>Make the first move with a new prompt.</p></div>}
        <div className="play-posts">{rows.map(row => <article className="play-post" key={row.id}>
          <div className="play-post-meta"><span className="pill pill-topic">{row.topic}</span><span>{row.user_id === user.id ? "YOUR POST" : "COMMUNITY"} · {new Intl.DateTimeFormat("en-US", { month: "short", day: "numeric", timeZone: "America/New_York" }).format(new Date(row.created_at))}</span></div>
          <p className="caption-copy play-caption">{row.content}</p>
          <VoteControls id={row.id} upvotes={Number(row.upvotes)} downvotes={Number(row.downvotes)} ownVote={Number(row.own_vote)} isOwn={row.user_id === user.id}/>
          <details className="play-prompt"><summary>VIEW PROMPT</summary><p className="caption-copy">{row.prompt}</p><small>GENERATED BY {row.provider}</small></details>
        </article>)}</div>
        {!feedError && <div className="pagination"><div>{page > 1 && <Link href={href(view, topic || null, page - 1)}>← PREVIOUS</Link>}</div><div>{rows.length === 20 && <Link href={href(view, topic || null, page + 1)}>NEXT →</Link>}</div></div>}
      </section>
      <aside className="play-sidebar">
        <section className="panel play-create"><div className="eyebrow dark">MAKE SOMETHING</div><h2>CRAFT A CAPTION</h2><p>Use the same publishing rules as every other player.</p><Composer/></section>
        <section className="panel play-drafts"><div className="eyebrow dark">MEMORY CARD</div><h2>YOUR DRAFTS</h2>{drafts?.length ? <ul>{(drafts as Draft[]).map(draft => <li key={draft.id}><span>{draft.topic}</span><p className="caption-copy">{draft.prompt}</p></li>)}</ul> : <p>No private drafts yet.</p>}</section>
      </aside>
    </div>
  </>;
}
